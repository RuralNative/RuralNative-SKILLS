  test("a real temp-file write is byte-identical on repeat and preserves hashes outside the block", () => {
    const cases = [
      "ordinary.md",
      "managed.md",
      "frontmatter.md",
      "stale.md",
      "protected.md",
      "duplicate.md",
      "unmatched.md",
    ] as const;
    const strip = (s: string) => s.replace(/<!-- unslopify:session-start:start -->[\s\S]*?<!-- unslopify:session-start:end -->/g, "");
    const sha = (s: string) => crypto.createHash("sha256").update(s).digest("hex");
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "unslopify-setup-hash-"));
    try {
      for (const fixture of cases) {
        const original = read(`skills/unslopify/tests/fixtures/agents-md/${fixture}`);
        const file = path.join(dir, fixture);
        fs.writeFileSync(file, original);
        const applied = applySetup(fs.readFileSync(file, "utf8"));
        fs.writeFileSync(file, applied);
        const second = applySetup(fs.readFileSync(file, "utf8"));
        assert.equal(sha(second), sha(fs.readFileSync(file, "utf8")), `${fixture}: a repeat run over the installed file must be byte-identical`);
        fs.writeFileSync(file, second);
        if (fixture === "protected.md" || fixture === "duplicate.md" || fixture === "unmatched.md") {
          assert.equal(sha(fs.readFileSync(file, "utf8")), sha(original), `${fixture}: no-edit case must keep the original bytes`);
          continue;
        }
        const onDisk = strip(fs.readFileSync(file, "utf8"));
        const onDiskOutside = fixture === "ordinary.md" ? onDisk.replace(/^\n\n/, "") : onDisk;
        assert.equal(sha(onDiskOutside), sha(strip(original)), `${fixture}: only the owned block bytes may differ from the original`);
        assert.equal(countBlocks(fs.readFileSync(file, "utf8")), 1, `${fixture}: exactly one owned block on disk`);
      }
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });

