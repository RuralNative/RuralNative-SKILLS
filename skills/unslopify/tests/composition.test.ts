const SESSION_BLOCK = [
  "<!-- unslopify:session-start:start -->",
  "Load `unslopify` before the first user-visible response in every session. Keep it active for all model-authored English questions and prose.",
  "<!-- unslopify:session-start:end -->",
].join("\n");

const BLOCK_RE = /<!-- unslopify:session-start:start -->[\s\S]*?<!-- unslopify:session-start:end -->/g;

function countBlocks(text: string): number {
  return (text.match(BLOCK_RE) ?? []).length;
}

const OWNED_RE = /<!-- unslopify:session-start:start -->[\s\S]*?<!-- unslopify:session-start:end -->/;

// Reference model for SKILL.md's Session-start setup rules 1-9. It mirrors the
// prose contract so the byte-level guarantees are machine-checked: an exact
// existing block is a no-op; a stale owned block gets only its body replaced;
// duplicate, unmatched, or nested markers and files another generator owns
// produce no edit; a managed file takes the block directly after the
// management-marker line; a file with valid frontmatter takes it directly
// after the frontmatter; a bare file takes it at byte zero followed by a blank
// separator. Insertion adds only the owned block (plus the one separator in
// the byte-zero case), so every pre-existing byte survives.
function applySetup(text: string): string {
  if (text.includes("generated by") || text.includes("another generator owns")) return text;
  const startCount = (text.match(/<!-- unslopify:session-start:start -->/g) ?? []).length;
  const endCount = (text.match(/<!-- unslopify:session-start:end -->/g) ?? []).length;
  const nested = /<!-- unslopify:session-start:start -->[\s\S]*?<!-- unslopify:session-start:start -->/.test(text);
  if (startCount !== endCount || startCount > 1 || nested) return text;
  if (OWNED_RE.test(text)) {
    if (text.includes(SESSION_BLOCK)) return text;
    return text.replace(OWNED_RE, SESSION_BLOCK);
  }
  const management = text.indexOf("<!-- managed: document-for-agents");
  if (management !== -1) {
    const lineEnd = text.indexOf("\n", management);
    const at = lineEnd === -1 ? text.length : lineEnd + 1;
    return text.slice(0, at) + SESSION_BLOCK + text.slice(at);
  }
  const fm = text.match(/^---\n[\s\S]*?\n---\n/);
  if (fm) return fm[0] + SESSION_BLOCK + text.slice(fm[0].length);
  return SESSION_BLOCK + "\n\n" + text;
}

